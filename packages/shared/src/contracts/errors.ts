export type ErrorCode =
  | 'VALIDATION_FAILED'
  | 'UNAUTHORIZED'
  | 'FORBIDDEN'
  | 'NOT_FOUND'
  | 'RATE_LIMITED'
  | 'USERNAME_TAKEN'
  | 'INVALID_CREDENTIALS'
  | 'WORLD_FULL'
  | 'INSUFFICIENT_RESOURCES'
  | 'BUILD_QUEUE_FULL'
  | 'REQUIREMENT_NOT_MET'
  | 'MAX_LEVEL_REACHED'
  | 'SLOT_TYPE_NOT_ALLOWED'
  | 'NOTHING_TO_CANCEL'
  | 'TRAINING_QUEUE_FULL'
  | 'HEALING_QUEUE_FULL'
  | 'NOT_ENOUGH_WOUNDED'
  | 'BATCH_TOO_LARGE' // acima do lote máx. do quartel (50 × nv)
  | 'TROOP_LOCKED' // tier não liberado pelo nível do quartel
  | 'COMMANDER_REQUIRED'
  | 'HERO_CANNOT_LEAD'
  | 'HERO_BUSY'
  | 'HERO_LOCKED' // herói ainda não liberado
  | 'HERO_MAX_LEVEL'
  | 'NOT_ENOUGH_FRAGMENTS'
  | 'TOO_MANY_HEROES'
  | 'NOT_ENOUGH_TROOPS'
  | 'NO_TROOPS'
  | 'MARCH_CAPACITY_EXCEEDED' // tropas acima da capacidade de marcha da Cidadela
  | 'MARCH_LIMIT_REACHED'
  | 'TARGET_INVALID' // nada daquele tipo naquela coordenada
  | 'TARGET_OWN_CITY'
  | 'TARGET_SHIELDED'
  | 'TARGET_DEPLETED'
  | 'TARGET_LEVEL_TOO_LOW' // Cidadela do alvo 4+ níveis abaixo
  | 'REINFORCE_CAPACITY_FULL'
  | 'MARCH_NOT_RECALLABLE'
  | 'CHEST_ALREADY_OPENED'
  | 'DAILY_CHEST_NOT_READY'
  | 'FREE_SUMMON_NOT_READY'
  | 'NOT_ENOUGH_ITEMS'
  | 'ITEM_NOT_USABLE'
  | 'INTERNAL';

export interface ApiError {
  statusCode: number;
  code: ErrorCode;
  /** Técnico, em inglês (log); a tela usa i18n pelo code. */
  message: string;
  /** Ex.: { missing: Resources } em INSUFFICIENT_RESOURCES. */
  details?: Record<string, unknown>;
}

